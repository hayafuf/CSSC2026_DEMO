  // 同色の隣接ペアが1つも無い状態が drought 秒続いたら発動する。
  // ※ 危機の解消に効くのは先頭グループを消すことだけなので、後方の離れた
  //    ペアは数えない(全域判定だと実戦でほぼ発動しない)。
