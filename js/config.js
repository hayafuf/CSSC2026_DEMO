  //   鈍く感じたら、この ATTRACT_MAX を上げて調整する。
  // 磁力で巻き戻っていた列は、コンボが途切れても急停止しない。
  // 合流 → 消去のあとも勢い(pull)を保ったまま巻き戻り続け、
  // 色が合わなくなったらこの時定数で減衰しながら滑って止まる。
