  PP.REVERSE_SPEED = 160;   // 逆風の初速(風速) px/s
  PP.REVERSE_ACCEL = 180;   // 逆風の加速度 px/s^2(発動からゆっくり風が強まる)
  PP.REVERSE_MAX = 1400;    // 逆風の最大風速 px/s(速い区間でも風が勝てる強さ)
  PP.REVERSE_RANGE = 700;   // 吹き戻しの上限距離 px(玉およそ15個ぶん。実後退で計上)
