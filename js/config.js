  // 効果時間(PP.POWERUPS の dur)は、風が流れに勝てず戻し切れない場合の
  // 保険の上限としてだけ働く。
  // ⚓ 錨との力関係は 逆風 > 錨(chain.js advance): 両方が効いていれば押し戻しが勝ち、
