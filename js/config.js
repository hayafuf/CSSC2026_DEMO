  // ---------- チェーンの速度プロファイル ----------
  // 速度はレール上の位置で決まる: 洞窟から出た直後は速く、
  // 樽(ゴール)に近づくほど少しずつ減速していく。
  //
  // 速度は「レール全長に対する位置」で決まるので、px/s の値が同じでも
  // レーンが短いコースほど洞窟から樽まで一瞬で届いてしまう。レーン長はコースにより
  // 1300px〜7500px と5倍以上違うため、この一式は「コースごとに設計するもの」として
  // 1つのプロファイルにまとめてある。コース定義に speed:{…} を書けば項目単位で
  // 上書きでき、書かなかった項目はこの既定のまま(PP.speedProfile 参照)。
  PP.SPEED = {
    entry:800,        // 洞窟付近の速度 px/s
    hole: 22,          // 樽の直前の速度 px/s
    curve: 1.3,        // 減速カーブの指数(大きいほど早めに減速する。小さいほど樽の奥まで速度を保つ)
    levelStep: 0.075,  // レベルごとの速度倍率の加算(0.06 → 0.075: 後半コースの hole 引き下げに負けて実効速度が下がっていたのを是正)
    rollout: 2.2,      // レベル開始時のなだれ込み加算倍率(減衰する)
    rolloutDecay: 0.5  // なだれ込み倍率の減衰時定数(秒)
  };

  // コース定義の speed(部分指定可)を既定へ重ねて、欠けのないプロファイルにする。
  // コースを組み直すたびに main.js の buildCourse が呼び、PP.game.speed へ入れる。
  PP.speedProfile = function (course) {
    var out = {}, src = (course && course.speed) || {};
    for (var k in PP.SPEED) {
      out[k] = (typeof src[k] === "number" && isFinite(src[k])) ? src[k] : PP.SPEED[k];
    }
    return out;
  };
  // 速度の基準位置(spdD)の追従。チェーンが分断されると、後ろの断片は
  // 「消える前の先頭」の位置=樽寄り=遅い速度を基準に持ったままになる。
  // それを永久に引きずると、洞窟のすぐそばにいる断片が樽の直前の速さで
  // 這うことになって不自然なので、少し待ってから自分の先頭位置へ寄せ直す。
  // (即座に切り替えると分断の瞬間に断片がガクンと加速して見える)
  PP.SPD_REF_HOLD = 0.45;  // 基準がずれてから追従を始めるまでの猶予(秒)
  PP.SPD_REF_RELAX = 0.9;  // 基準が自分の先頭へ寄る時定数(秒)

  // ---------- 磁力巻き戻しと衝突の反動 ----------
  // 隙間の前後が同色なら、前の列が加速しながら吸い寄せられ、
  // ぶつかった勢いで「ぶつけられた後ろの列」が洞窟方向へ押し戻される
  PP.ATTRACT_SPEED = 250;        // 磁力の初速 px/s
  PP.ATTRACT_ACCEL = 1300;       // 磁力の加速度 px/s^2(近いほど速く吸い込まれる)
